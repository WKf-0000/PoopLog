#define WARN_LOG(msg) ::poop::log(::poop::level::lv_WARN , msg)
#define ERROR_LOG(msg) ::poop::log(::poop::level::lv_ERROR , msg)
#define OTHER_LOG(msg) ::poop::log(::poop::level::lv_OTHER , msg)

